"""Writes src/interpreter/vb_case_table.hpp from the case probe.

evidence/reference/case-probe/vb6-reference.txt holds, for every character
whose UCase or LCase differs from itself under Visual Basic 6, its code and the
codes of its UCase and LCase (hexadecimal, "code = upper lower"). The header is
the table the interpreter uses for UCase, LCase, StrConv and text comparison.

Usage (from the repository root):
    python scripts/New-CaseTable.py
"""

import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
source = os.path.join(root, "evidence", "reference", "case-probe",
                      "vb6-reference.txt")
target = os.path.join(root, "src", "interpreter", "vb_case_table.hpp")

entries = []
with open(source, newline="") as handle:
    for line in handle.read().replace("\r", "").split("\n"):
        if line:
            code, rest = line.split(" = ")
            upper, lower = rest.split(" ")
            numbers = (code, upper, lower)
            entries.append(tuple(int(part, 16) for part in numbers))
entries.sort()

lines = [
    "// UCase and LCase of every character that has one, as Visual Basic 6",
    "// answers them (generated by scripts/New-CaseTable.py from",
    "// evidence/reference/case-probe/vb6-reference.txt; do not edit).",
    "",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace wfc::detail {",
    "",
    "struct CaseEntry {",
    "    std::uint16_t code;",
    "    std::uint16_t upper;",
    "    std::uint16_t lower;",
    "};",
    "",
    "inline constexpr CaseEntry kCaseTable[] = {",
]
row = "   "
for code, upper, lower in entries:
    item = " {0x%04X, 0x%04X, 0x%04X}," % (code, upper, lower)
    if len(row) + len(item) > 80:
        lines.append(row)
        row = "   "
    row += item
lines.append(row)
lines += ["};", "", "}  // namespace wfc::detail", ""]
with open(target, "w", newline="\n") as handle:
    handle.write("\n".join(lines))
print("wrote", len(entries), "entries to", target)
