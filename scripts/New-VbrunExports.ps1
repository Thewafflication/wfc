#Requires -Version 7
<#
.SYNOPSIS
    Generates the export list of the VBRUN compatibility library from the
    retained MSVBVM60 inventory (REQ-0105).
.DESCRIPTION
    Writes src/vbrun/wfcvbrun.def (ordinals and names) and
    src/vbrun/vbrun_exports.inc (one VBRUN_EXPORT(ordinal, name) per named
    export). Slots that are empty in the reference stay empty.
#>
[CmdletBinding()]
param(
    [string]$Evidence = (Join-Path $PSScriptRoot `
        '..\evidence\reference\msvbvm60-6.0-runtime.json'),
    [string]$Output = (Join-Path $PSScriptRoot '..\src\vbrun')
)

$ErrorActionPreference = 'Stop'
$inventory = Get-Content -Raw -LiteralPath $Evidence | ConvertFrom-Json
$directory = $inventory.exportDirectory
$present = @($directory.exports | Where-Object { $_.present })
if ($directory.ordinalBase -ne 100 -or
    $present.Count -ne $directory.namedExports) {
    throw 'The inventory does not have the expected shape.'
}

$script = 'scripts/New-VbrunExports.ps1'
$def = [System.Text.StringBuilder]::new()
$null = $def.AppendLine("; Generated by $script from")
$null = $def.AppendLine('; evidence/reference/msvbvm60-6.0-runtime.json.')
$null = $def.AppendLine('; Do not edit.')
$null = $def.AppendLine('LIBRARY wfcvbrun')
$null = $def.AppendLine('EXPORTS')
$inc = [System.Text.StringBuilder]::new()
$null = $inc.AppendLine("// Generated by $script. Do not edit.")
foreach ($export in $present) {
    $line = '    {0}=vbrun_stub_{1} @{1}'
    $null = $def.AppendLine(($line -f $export.name, $export.ordinal))
    $line = 'VBRUN_EXPORT({0}, {1})'
    $null = $inc.AppendLine(($line -f $export.ordinal, $export.name))
}

New-Item -ItemType Directory -Force -Path $Output | Out-Null
$defPath = Join-Path $Output 'wfcvbrun.def'
$incPath = Join-Path $Output 'vbrun_exports.inc'
[System.IO.File]::WriteAllText($defPath, $def.ToString())
[System.IO.File]::WriteAllText($incPath, $inc.ToString())
Write-Host ('Wrote {0} exports to {1}' -f $present.Count, $Output)
