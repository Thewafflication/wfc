<#
.SYNOPSIS
Generates the form and control member tables from the VB6 type-library
evidence.

.DESCRIPTION
Reads evidence/reference/vb-6.0-type-library.json and writes
lib/wfc-ocx/src/control_tables.cpp: for every VB runtime class, its default-interface
members (properties, methods) and its event-interface members, with types,
member identifiers and parameters. The output is unformatted C++; run
clang-format over it before committing. The file records the SHA-256 of the
evidence so a CTest check can detect drift.

.PARAMETER EvidencePath
Path of the type-library evidence JSON.

.PARAMETER OutputPath
Path of the generated C++ source.

.PARAMETER ClassProperty
Name of the evidence property that lists the classes (`classes` for the VB
library, `controls` for MSComctlLib).

.PARAMETER FunctionName
Name of the generated accessor (`control_classes` or `comctl_classes`).

.EXAMPLE
pwsh -NoProfile -File lib/wfc-ocx/scripts/New-UiControlTables.ps1
#>
[CmdletBinding()]
param(
    [Parameter()]
    [string] $EvidencePath = 'evidence/reference/vb-6.0-type-library.json',

    [Parameter()]
    [string] $OutputPath = 'lib/wfc-ocx/src/control_tables.cpp',

    [Parameter()]
    [string] $ClassProperty = 'classes',

    [Parameter()]
    [string] $FunctionName = 'control_classes'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function ConvertTo-KindCode {
    param([string] $Kind)
    switch ($Kind) {
        'PropertyGet' { return 'g' }
        'PropertyLet' { return 'l' }
        'PropertyPut' { return 's' }
        'PropertySet' { return 's' }
        'PropertyPutRef' { return 's' }
        default { return 'm' }
    }
}

function Format-ParameterList {
    param($Parameters)
    $items = @()
    foreach ($parameter in $Parameters) {
        $suffix = ''
        if ($parameter.optional) {
            $suffix = ':o'
        }
        $items += ('{0}:{1}{2}' -f $parameter.name, $parameter.type, $suffix)
    }
    return ($items -join ';')
}

function Format-MemberRow {
    param($Members)
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($member in $Members) {
        $kind = ConvertTo-KindCode $member.kind
        $parameters = Format-ParameterList $member.parameters
        $lines.Add(('    {{"{0}", ''{1}'', "{2}", {3}, "{4}"}},' -f
                $member.name, $kind, $member.returnType, $member.memberId,
                $parameters))
    }
    return $lines
}

$evidence = Get-Content -LiteralPath $EvidencePath -Raw | ConvertFrom-Json
# Hash the evidence with line endings normalized, so a checkout that converts
# CRLF to LF (or back) does not change the recorded value.
$latin1 = [System.Text.Encoding]::GetEncoding(28591)
$raw = $latin1.GetString([System.IO.File]::ReadAllBytes(
        (Resolve-Path -LiteralPath $EvidencePath).Path))
$normalized = $raw.Replace("`r`n", "`n")
$sha = [System.Security.Cryptography.SHA256]::Create()
$hash = ([System.BitConverter]::ToString(
        $sha.ComputeHash($latin1.GetBytes($normalized)))).Replace('-', '')
$hash = $hash.ToLowerInvariant()

$text = New-Object System.Collections.Generic.List[string]
$text.Add('// Generated by lib/wfc-ocx/scripts/New-UiControlTables.ps1; do not edit.')
$text.Add("// Source: $EvidencePath")
$text.Add("// SHA256: $hash")
$text.Add('')
$text.Add('#include "control_tables.hpp"')
$text.Add('')
$text.Add('namespace wfc::ui {')
$text.Add('namespace {')
$text.Add('')

$classes = @($evidence.$ClassProperty | Where-Object { $_.defaultInterface })
$index = 0
foreach ($class in $classes) {
    $members = @(Format-MemberRow $class.defaultInterface.members)
    $text.Add("const MemberRow kMembers$index[] = {")
    foreach ($line in $members) { $text.Add($line) }
    $text.Add('};')
    $events = @()
    if ($class.PSObject.Properties['defaultEventInterface'] -and
        $class.defaultEventInterface) {
        $events = @(Format-MemberRow $class.defaultEventInterface.members)
    }
    if ($events.Count -gt 0) {
        $text.Add("const MemberRow kEvents$index[] = {")
        foreach ($line in $events) { $text.Add($line) }
        $text.Add('};')
    }
    $text.Add('')
    $index++
}

$text.Add('const ControlClass kClasses[] = {')
$index = 0
foreach ($class in $classes) {
    $eventName = 'nullptr'
    $eventCount = 0
    if ($class.PSObject.Properties['defaultEventInterface'] -and
        $class.defaultEventInterface -and
        @($class.defaultEventInterface.members).Count -gt 0) {
        $eventName = "kEvents$index"
        $eventCount = @($class.defaultEventInterface.members).Count
    }
    $memberCount = @($class.defaultInterface.members).Count
    $text.Add(('    {{"{0}", kMembers{1}, {2}, {3}, {4}}},' -f
            $class.name, $index, $memberCount, $eventName, $eventCount))
    $index++
}
$text.Add('};')
$text.Add('')
$text.Add('}  // namespace')
$text.Add('')
$text.Add("std::span<const ControlClass> $FunctionName() {")
$text.Add('    return kClasses;')
$text.Add('}')
$text.Add('')
$text.Add('}  // namespace wfc::ui')

$directory = Split-Path -Parent $OutputPath
if ($directory -and -not (Test-Path -LiteralPath $directory)) {
    New-Item -ItemType Directory -Path $directory | Out-Null
}
Set-Content -LiteralPath $OutputPath -Value $text -Encoding utf8
